def get_active_digests():
    """Return all non-expired digests with their articles."""

    connection = get_connection()

    try:
        with connection.cursor() as cursor:

            cursor.execute("""
                SELECT
                    d.id AS digest_id,
                    d.created_at,
                    d.expires_at,

                    a.id AS article_id,
                    a.title,
                    a.url,
                    a.published,
                    a.summary,
                    a.source,
                    a.category,
                    a.score

                FROM digests d

                JOIN digest_articles da
                    ON d.id = da.digest_id

                JOIN articles a
                    ON da.article_id = a.id

                WHERE d.expires_at > CURRENT_TIMESTAMP

                ORDER BY
                    d.created_at DESC,
                    a.score DESC
            """)

            rows = cursor.fetchall()

            digests = {}

            for row in rows:

                digest_id = row["digest_id"]

                if digest_id not in digests:
                    digests[digest_id] = {
                        "id": digest_id,
                        "created_at": row["created_at"],
                        "expires_at": row["expires_at"],
                        "articles": [],
                    }

                digests[digest_id]["articles"].append({
                    "id": row["article_id"],
                    "title": row["title"],
                    "url": row["url"],
                    "published": row["published"],
                    "summary": row["summary"],
                    "source": row["source"],
                    "category": row["category"],
                    "score": row["score"],
                })

            return list(digests.values())

    finally:
        connection.close()


def set_article_read_status(
    article_id: int,
    is_read: bool,
):
    """Set whether an article has been read."""

    connection = get_connection()

    try:
        with connection.cursor() as cursor:

            cursor.execute("""
                UPDATE articles
                SET is_read = %s
                WHERE id = %s
            """, (
                1 if is_read else 0,
                article_id,
            ))

            updated = cursor.rowcount > 0

        connection.commit()

        return updated

    finally:
        connection.close()

