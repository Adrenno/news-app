def get_articles(
    limit=20,
    offset=0,
    category=None,
    source=None,
    search=None,
    is_read=None,
):
    """Return paginated articles with optional filters."""

    connection = get_connection()

    try:
        with connection.cursor() as cursor:

            query = """
                SELECT *
                FROM articles
            """

            conditions = []
            parameters = []

            if category is not None:
                conditions.append("category = %s")
                parameters.append(category)

            if source is not None:
                conditions.append("source = %s")
                parameters.append(source)

            if search:
                conditions.append(
                    "(title ILIKE %s OR summary ILIKE %s)"
                )

                search_term = f"%{search}%"

                parameters.extend([
                    search_term,
                    search_term,
                ])

            if is_read is not None:
                conditions.append("is_read = %s")
                parameters.append(1 if is_read else 0)

            if conditions:
                query += (
                    " WHERE "
                    + " AND ".join(conditions)
                )

            query += """
                ORDER BY score DESC, id DESC
                LIMIT %s
                OFFSET %s
            """

            parameters.extend([
                limit,
                offset,
            ])

            cursor.execute(
                query,
                parameters,
            )

            return cursor.fetchall()

    finally:
        connection.close()


def get_recent_articles(hours: int = 12):
    """Return articles first seen within the last N hours."""

    connection = get_connection()

    try:
        with connection.cursor() as cursor:

            cursor.execute("""
                SELECT *
                FROM articles
                WHERE created_at >=
                    CURRENT_TIMESTAMP - (%s * INTERVAL '1 hour')
                ORDER BY score DESC
            """, (hours,))

            return cursor.fetchall()

    finally:
        connection.close()


def create_digest_record(articles: list[dict]):
    """Create a digest and associate articles with it."""

    connection = get_connection()

    try:
        with connection.cursor() as cursor:

            cursor.execute("""
                INSERT INTO digests (
                    expires_at
                )
                VALUES (
                    CURRENT_TIMESTAMP
                    + INTERVAL '12 hours'
                )
                RETURNING id
            """)

            digest_id = cursor.fetchone()["id"]

            for article in articles:

                cursor.execute("""
                    INSERT INTO digest_articles (
                        digest_id,
                        article_id
                    )
                    VALUES (%s, %s)
                """, (
                    digest_id,
                    article["id"],
                ))

        connection.commit()

        return digest_id

    finally:
        connection.close()


def get_digests(
    limit: int = 20,
    offset: int = 0,
    digest_id: int | None = None,
):
    """Return recent digests with their associated articles."""

    connection = get_connection()

    try:
        with connection.cursor() as cursor:

            if digest_id is not None:

                cursor.execute("""
                    SELECT id, created_at, expires_at
                    FROM digests
                    WHERE id = %s
                """, (digest_id,))

            else:

                cursor.execute("""
                    SELECT id, created_at, expires_at
                    FROM digests
                    ORDER BY created_at DESC, id DESC
                    LIMIT %s
                    OFFSET %s
                """, (
                    limit,
                    offset,
                ))

            digest_rows = cursor.fetchall()

            digests = []

            for digest in digest_rows:

                cursor.execute("""
                    SELECT
                        a.id,
                        a.title,
                        a.url,
                        a.published,
                        a.summary,
                        a.source,
                        a.category,
                        a.score,
                        a.is_read
                    FROM digest_articles da
                    JOIN articles a
                        ON a.id = da.article_id
                    WHERE da.digest_id = %s
                    ORDER BY a.score DESC
                """, (digest["id"],))

                articles = cursor.fetchall()

                digests.append({
                    "id": digest["id"],
                    "created_at": digest["created_at"],
                    "expires_at": digest["expires_at"],
                    "articles": articles,
                })

            return digests

    finally:
        connection.close()


def get_last_digest_time():
    """Return the timestamp of the most recent digest."""

    connection = get_connection()

    try:
        with connection.cursor() as cursor:

            cursor.execute("""
                SELECT created_at
                FROM digests
                ORDER BY created_at DESC
                LIMIT 1
            """)

            result = cursor.fetchone()

            if result is None:
                return None

            return result["created_at"]

    finally:
        connection.close()


